"""README.md (data card) of $EMDATA_ROOT, written by emseg.data.stages.report from live numbers."""
import json

from emseg.data.standard import DATA_ROOT, STANDARD, CLASSES, MIN_CC, BLANK_STD, MIN_VALID_FRAC, MIN_INST_DENSE
from emseg.data.registry import SOURCES


def _tab(rows, cols, head):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out)


def write_readme(rows, summ, dls, now):
    em, mix = summ.get("em_only", {}), summ.get("em_plus_natural", {})
    groups = (("A. Dense cell / neurite instances (expert labels, gold)", lambda r: "cell" in r["classes"] and r["quality"] == "gold"),
              ("B. Dense cell instances (automatic connectome segmentations, silver)", lambda r: "cell" in r["classes"] and r["quality"] == "silver"),
              ("C. Organelle / particle instances (only the listed classes are annotated)", lambda r: "cell" not in r["classes"] and r["classes"] != "natural_segment"),
              ("D. Natural images (auxiliary)", lambda r: r["classes"] == "natural_segment"))
    T = []
    for title, f in groups:
        rs = [dict(r) for r in rows if f(r)]
        if not rs:
            continue
        for r in rs:
            r["drop_c"] = ", ".join(f"{k} {v}" for k, v in json.loads(r["convert_dropped"]).items()) or "-"
            r["drop_f"] = ", ".join(f"{k} {v}" for k, v in json.loads(r["filtered"]).items()) or "-"
            r["final"] = f"{r['final_images']} ({r['final_train']}/{r['final_val']})" if not r["excluded"] else f"0 (excluded: {r['excluded'][:60]})"
            r["mass"] = f"{float(r['mass_em_only'] or 0):.3f} / {float(r['mass_em_plus_natural'] or 0):.3f}"
        T.append(f"\n### {title}\n\n" + _tab(sorted(rs, key=lambda r: -int(r["final_images"] or 0)),
                 ["dataset", "content", "modality", "res_nm", "classes", "src_images", "drop_c", "converted", "drop_f", "final", "pct_of_em_images", "mass"],
                 ["dataset", "content", "modality", "pixel size nm", "classes", "source images", "dropped at conversion", "converted", "filtered (F1-F7)", "final (train/val)", "% of EM images", "sampling mass EM / EM+natural"]))
    src_rows = []
    for s in SOURCES:
        d = dls.get(s.id, {})
        links = "<br>".join(f"`{u}`" for _, u, _, _ in s.files[:4]) + (f"<br>... {len(s.files)} files in total" if len(s.files) > 4 else "")
        src_rows.append({"id": f"`{s.id}`", "name": s.name, "home": s.homepage, "method": s.method, "links": links or "(streamed, see registry)",
                         "lic": s.license, "cite": s.citation, "dl": f"{d.get('state', '')} {d.get('present', '')}/{d.get('files', '')}",
                         "note": ("**off by default**: " if not s.default else "") + s.rules.replace("|", "/")})
    txt = f"""# Multi-source 2D EM instance-segmentation corpus ({STANDARD})

> Generated by `python -m emseg.data.stages.report` ({now}); every number is recomputed from the files on disk and `pipeline_log.jsonl`.
> Live status: `STATUS.md`; machine-readable per-dataset table: `datasets.csv`; how and why each stage works: `emseg/data/README.md` of the code repository.
> One-click rebuild: `scripts/10_build_corpus.sh` (resumable; finished stages are skipped).

## 1. Training manifests

| manifest | rows | train / val / gap | contents |
|---|---|---|---|
| `manifests/em_only.csv` | {em.get('rows', '')} | {em.get('train', '')} / {em.get('val', '')} / {em.get('gap', '')} | EM only |
| `manifests/em_plus_natural.csv` | {mix.get('rows', '')} | - | plus {mix.get('natural_rows', '')} COCO natural images carrying {100 * mix.get('natural_mass', 0):.0f}% of the sampling mass |

Columns: `uid, group, dataset, file, key, z, z_src, H, W, res_xy_nm, res_z_nm, classes, n_inst, quality, modality, organism, split, weight`.
Reading: volumes `f['raw'][z]`, `f['labels/<class>'][z]`, `f['masks/<class>'][z]` (`file` = em/<dataset>/<volume>.h5); 2D collections and natural images `f[key]['raw']`, `f[key]['labels/<class>']`.
`weight` is the sampling probability of a train row (sums to 1); `val` is for monitoring only, not a benchmark; `gap` rows are isolation sections before the validation block (unused).

**Class vocabulary**: {', '.join(f'{k}={v}' for k, v in CLASSES.items())}. `classes` lists the annotated classes of an image; a class that is not listed is *unknown* on that image
(partial-label convention): the background of a mitochondria dataset contains unlabelled cells and must not be used as "no cell" supervision.

Filtered in total: {summ.get('filtered_total', '')} images (by reason {json.dumps(summ.get('filtered_by_reason', {}))});
datasets excluded by de-duplication / leakage: {json.dumps(summ.get('excluded_datasets', {})) or 'none'}.

## 2. Composition (per dataset: source images -> converted -> QA-filtered -> final)
{''.join(T)}

Column notes: source images = slices / images read by the converter (after leakage exclusions); dropped at conversion = padding / blank / no_label / sparse_label / degenerate_label;
filtered = F1 too small, F2 saturated, F3 blurred, F4 degenerate labels, F5 labels not on membranes, F6 duplicate, F7 dataset excluded; % of EM images = final images / all final EM images.

## 3. Sources and download links
{_tab(src_rows, ['id', 'name', 'home', 'method', 'links', 'lic', 'cite', 'dl', 'note'], ['id', 'name', 'homepage', 'method', 'download links', 'licence', 'citation', 'download state', 'rules / notes'])}

Per-file record (URL, bytes, sha256, comparison with the publisher's checksum, time): `provenance/downloads.csv`; every download / conversion event: `pipeline_log.jsonl`.

## 4. Unified standard and cleaning rules (summary; rationale in `emseg/data/README.md`)

- Format: one HDF5 per source volume: `raw` uint8 (P0.5/P99.5 linear stretch), `labels/<class>` uint32 (per-slice 4-connected 2D instances, consecutive ids), `masks/<class>` uint8, `label_src/<class>` (source ids); attributes record source, licence, pixel size and kept / dropped slices.
- Cleaning at conversion: slices with < {MIN_VALID_FRAC:.0%} valid area (padding) or grey std < {BLANK_STD} (blank) are dropped; components < {MIN_CC} px are masked out; dense classes with < 30 % labelled area or < {MIN_INST_DENSE} instances are unusable on that slice.
- QA filters (F1-F5), de-duplication (F6: md5 exact duplicates, pHash + thumbnail correlation near duplicates), cross-dataset region overlap and benchmark-leakage scan (F7: template matching at a common 32 nm scale).
- Leakage: SNEMI only AC4 z0-79, CREMI only z0-74, mouse_30um never in the manifests; every validation / test slice of the project's benchmarks is used as a query against the whole corpus (`dedup/region_overlap.csv`, query = BENCH).
- Splits: validation by volume / source group, 2-section gap inside volumes; weights: dataset mass proportional to sqrt(labelled pixels), silver x0.5.

## 5. Layout

```
README.md  STATUS.md  datasets.csv  pipeline_log.jsonl  checksums.sha256
manifests/   em_only.csv  em_plus_natural.csv  summary.json
em/<dataset>/<volume>.h5      em2d/<dataset>/shard_*.h5 (+index.csv, build_summary.json)      natural/coco_panoptic/{{train,val}}/
qa/images.csv  qa/filter_log.csv          dedup/duplicates.csv  dedup/region_overlap.csv  dedup/decisions.json
provenance/downloads.csv                  raw_downloads/ (original downloads; may be deleted once verified)      local/ (non-public data, off by default)
_qc/ (3 preview slices per volume)  _build_logs/ (conversion logs)
```
"""
    (DATA_ROOT / "README.md").write_text(txt)
